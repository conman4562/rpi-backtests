"""Generate SQL that gives courses their catalog names, for courses whose name is still just their code.

Courses created by a backtest upload get name = code, because the file name has no title. This reads
each catalog.json course from the running backend (GET /courses?query=<code>, read-only), finds the
ones whose stored name still equals the code, and writes update_course_names.sql with one UPDATE per
course. Nothing is changed in the database by this script; run the SQL file yourself (for example in
the Supabase SQL editor).

Every UPDATE is guarded with "AND name = code", so a name that was already fixed or set by hand is
never overwritten.

The backend URL comes from --url, the COURSES_API_URL environment variable, or COURSES_API_URL in
backend/.env, defaulting to http://127.0.0.1:8080/courses.

Usage:
  python update_course_names.py [--catalog FILE] [--url URL] [--out FILE] [--workers N]
"""

import argparse
import json
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from populate_courses import DEFAULT_CATALOG, DEFAULT_URL, read_env_var

DEFAULT_OUT = Path(__file__).resolve().parent / "update_course_names.sql"
MISSING = object()


def stored_name(url, code):
    """Returns the name stored for code, MISSING if the course doesn't exist, or raises on a request failure.

    GET /courses returns invalid JSON when a course has backtests (Course.tests and BackTest.course
    point at each other), but each course still starts with its intact code and name, so those fields
    are read straight from the text instead of parsing the whole response.
    """
    query = urllib.parse.urlencode({"query": code})
    with urllib.request.urlopen(f"{url}?{query}", timeout=60) as response:
        body = response.read().decode("utf-8")
    match = re.search(r'"code":"' + re.escape(code) + r'","name":"((?:[^"\\]|\\.)*)"', body)
    return json.loads(f'"{match.group(1)}"') if match else MISSING


def sql_str(value):
    return "'" + value.replace("'", "''") + "'"


def build_sql(updates):
    lines = [
        "-- Generated by automation_scripts/update_course_names.py.",
        "-- Only changes courses whose name is still equal to their code.",
        "BEGIN;",
        "",
    ]
    for code, name in updates:
        lines.append(f"UPDATE course SET name = {sql_str(name)} WHERE code = {sql_str(code)} AND name = code;")
    lines += ["", "COMMIT;", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG)
    ap.add_argument("--url", default=read_env_var("COURSES_API_URL") or DEFAULT_URL)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()

    catalog = json.loads(args.catalog.read_text(encoding="utf-8"))
    names = {code: (entry.get("name") or "").strip() for code, entry in sorted(catalog.items())}

    def check(code):
        return code, stored_name(args.url, code)

    updates, missing = [], []
    try:
        with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
            for code, current in pool.map(check, names):
                if current is MISSING:
                    missing.append(code)
                elif current == code and names[code] and names[code] != code:
                    updates.append((code, names[code]))
    except urllib.error.URLError as err:
        sys.exit(f"can't reach {args.url} ({err.reason}); is the backend running?")

    args.out.write_text(build_sql(updates), encoding="utf-8", newline="\n")
    print(f"{len(names)} catalog courses checked, {len(updates)} need a name, {len(missing)} not in the database")
    print(f"wrote {args.out}")
    for code, name in updates:
        print(f"  {code} -> {name}")
    if missing:
        print(f"not in the database: {', '.join(missing[:20])}{' ...' if len(missing) > 20 else ''}")


if __name__ == "__main__":
    main()
